"""Emit metadata-only identities from a separately supplied original Victory SHPI."""
from pathlib import Path
import argparse, hashlib, struct

DECODED_SHA = "373ba8d60b0ec3cc52cc65177ee234541c604e3fe08a7b0bc36f0b5f3f0d3ba6"
NAMES = ("back", "mcf1", "ff50", "f355", "fgt9", "find", "fmus", "jagr",
         "lgt1", "lesp", "nazc", "cala", "isde", "bbfs", "dayt", "fzr2")

def prepare(source, output):
    data = Path(source).read_bytes()
    if hashlib.sha256(data).hexdigest() != DECODED_SHA:
        raise ValueError("Unexpected original Victory archive")
    magic, size, count = struct.unpack_from("<4sII", data)
    if magic != b"SHPI" or size != len(data) or count != 28:
        raise ValueError("Unexpected archive directory")
    entries = [struct.unpack_from("<4sI", data, 16 + 8*i) for i in range(count)]
    offsets = [offset for _, offset in entries] + [len(data)]
    if offsets != sorted(set(offsets)) or offsets[0] < 16 + 8*count:
        raise ValueError("Invalid resource spans")
    resources = {name.decode("ascii"): data[offsets[i]:offsets[i+1]]
                 for i, (name, _) in enumerate(entries)}
    rows = []
    for image, name in enumerate(NAMES):
        raw = resources[name]
        kind, width, height = struct.unpack_from("<IHH", raw)
        position = struct.unpack_from("<I", raw, 12)[0]
        left = position & 4095
        top = (position >> 16) & 4095
        left = left-4096 if left & 2048 else left
        top = top-4096 if top & 2048 else top
        if kind != 0x78 or not (0 < width <= 640 and 0 < height <= 480):
            raise ValueError("Unexpected RGB565 image")
        if not 0 <= len(raw)-16-width*height*2 <= 3:
            raise ValueError("Unexpected pixel span or alignment")
        if left < 0 or top < 0 or left+width > 640 or top+height > 480:
            raise ValueError("Unexpected intrinsic placement")
        if image == 0 and (width, height, left, top) != (640, 480, 0, 0):
            raise ValueError("Unexpected background geometry")
        digest = ",".join(str(x) for x in hashlib.sha256(raw).digest())
        rows.append('{"%s",%d,%d,%d,%d,%d,%d,{%s}},' %
                    (name, image, width, height, left, top, len(raw), digest))
    text = """// SPDX-License-Identifier: MIT
// Generated by prepare_victory_original_artwork.py; metadata only, no original pixels.
#pragma once
#include <cstdint>
#include <cstring>
namespace nfs_victory_original {
// image=0 backdrop; image=1+original car index from table414C48.
struct Source {char name[5];unsigned image,width,height;int left,top;unsigned span;unsigned char sha[32];};
static const Source sources[16]={
""" + "\n".join(rows) + """
};
// Identity lookup only. Does not authorize a scene, target or drawing operation.
inline const Source*find(const unsigned char name[4])noexcept{
 if(!name)return nullptr;
 for(const auto&s:sources)if(!std::memcmp(s.name,name,4))return &s;
 return nullptr;
}
}
"""
    Path(output).write_bytes(text.encode("ascii"))
    return len(rows)

if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source",type=Path)
    parser.add_argument("output",type=Path)
    args=parser.parse_args()
    print("Prepared",prepare(args.source,args.output),"metadata-only image identities")
